    [Fact]
    public void SqliteSource_ToSqlServer_BasicTypes()
    {
        // Khóa chiều ngược SQLite → SQL Server qua affinity TEXT/INTEGER/REAL.
        Assert.Equal(CanonicalType.String, DbTypeMappers.ParseSqlite("TEXT").Type);
        Assert.Equal(CanonicalType.Int64, DbTypeMappers.ParseSqlite("INTEGER").Type);
        Assert.Equal(CanonicalType.Double, DbTypeMappers.ParseSqlite("REAL").Type);
        var table = new CanonicalTable
        {
            Name = "notes",
            Columns = new List<CanonicalColumn>
            {
                new() { Name = "Id", Type = CanonicalType.Int64, IsNullable = false },
                new() { Name = "Body", Type = CanonicalType.String, MaxLength = -1, IsNullable = true },
                new() { Name = "Score", Type = CanonicalType.Double, IsNullable = true }
            },
            PrimaryKeyColumns = new List<string> { "Id" }
        };
        var sql = CanonicalDdl.EmitSqlServer(table, out var warnings);

        Assert.Contains("BIGINT", sql);
        Assert.Contains("NVARCHAR(MAX)", sql);
        Assert.Contains("FLOAT(53)", sql);
        Assert.Single(warnings); // thiếu schema → cảnh báo dùng dbo mặc định.
    }
}
