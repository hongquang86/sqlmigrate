    [Fact]
    public void PgSource_ToSqlServer_TypesAndDefaults()
    {
        // Khóa chiều ngược PG → SQL Server: timestamptz/uuid/boolean/jsonb/text.
        CanonicalColumn Col(string name, string pgType, string? def = null)
        {
            var spec = DbTypeMappers.ParsePostgres(pgType);
            return new CanonicalColumn
            {
                Name = name, Type = spec.Type, MaxLength = spec.MaxLength,
                Precision = spec.Precision, Scale = spec.Scale,
                IsNullable = true, DefaultSql = def
            };
        }
        var table = new CanonicalTable
        {
            Schema = "public",
            Name = "events",
            Columns = new List<CanonicalColumn>
            {
                Col("ts", "timestamp with time zone"),
                Col("uid", "uuid"),
                Col("active", "boolean", "true"),
                Col("payload", "jsonb"),
                Col("note", "text")
            }
        };
        var sql = CanonicalDdl.EmitSqlServer(table, out var warnings);

        Assert.Contains("DATETIMEOFFSET", sql);
        Assert.Contains("UNIQUEIDENTIFIER", sql);
        Assert.Contains("BIT DEFAULT 1", sql);
        Assert.Contains("NVARCHAR(MAX)", sql);
        Assert.NotEmpty(warnings); // jsonb về SQL Server phải có cảnh báo.
    }

