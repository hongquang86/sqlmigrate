using System.Collections.Generic;
using SqlMigrator.Core.Models;
using SqlMigrator.Core.Services.DataMove;
using Xunit;

namespace SqlMigrator.Tests;

public class CanonicalDdlTests
{
    private static CanonicalTable Orders()
    {
        return new CanonicalTable
        {
            Schema = "dbo",
            Name = "Orders",
            Columns = new List<CanonicalColumn>
            {
                new() { Name = "Id", Type = CanonicalType.Int32, IsPrimaryKey = true, IsIdentity = true, IsNullable = false },
                new() { Name = "Code", Type = CanonicalType.String, MaxLength = 50, IsUnicode = true, IsNullable = false, DefaultSql = "'X'" },
                new() { Name = "Total", Type = CanonicalType.Decimal, Precision = 10, Scale = 2, IsNullable = true },
                new() { Name = "Created", Type = CanonicalType.DateTime, Scale = 7, IsNullable = false, DefaultSql = "SYSUTCDATETIME()" },
                new() { Name = "RowId", Type = CanonicalType.Guid, IsNullable = false }
            },
            PrimaryKeyColumns = new List<string> { "Id" },
            ForeignKeys = new List<CanonicalForeignKey>
            {
                new()
                {
                    Name = "FK_Orders_Customers",
                    Columns = new List<string> { "Code" },
                    RefSchema = "dbo",
                    RefTable = "Customers",
                    RefColumns = new List<string> { "Code" }
                }
            }
        };
    }

    [Fact]
    public void EmitPostgres_QuotesAllAndIdentity()
    {
        var sql = CanonicalDdl.EmitPostgres(Orders(), out var warnings);

        Assert.Contains("CREATE TABLE \"dbo\".\"Orders\"", sql);
        Assert.Contains("\"Id\" INTEGER GENERATED BY DEFAULT AS IDENTITY", sql);
        Assert.Contains("\"Code\" VARCHAR(50) NOT NULL DEFAULT 'X'", sql);
        Assert.Contains("\"Total\" NUMERIC(10,2)", sql);
        Assert.Contains("\"Created\" TIMESTAMP(7)", sql);
        Assert.Contains("PRIMARY KEY (\"Id\")", sql);
        Assert.Contains("CONSTRAINT \"FK_Orders_Customers\" FOREIGN KEY (\"Code\")", sql);
        Assert.Contains("REFERENCES \"dbo\".\"Customers\" (\"Code\")", sql);
        Assert.DoesNotContain("SYSUTCDATETIME()", sql);
        Assert.Empty(warnings);
    }

    [Fact]
    public void EmitSqlite_SingleIntegerPkInline()
    {
        var sql = CanonicalDdl.EmitSqlite(Orders(), out var warnings);

        Assert.Contains("CREATE TABLE \"Orders\"", sql);
        Assert.Contains("\"Id\" INTEGER PRIMARY KEY", sql);
        Assert.Contains("\"RowId\" TEXT", sql);
        Assert.DoesNotContain("dbo", sql);
        Assert.NotEmpty(warnings);
    }

    [Fact]
    public void EmitSqlServer_RoundTripBasics()
    {
        var sql = CanonicalDdl.EmitSqlServer(Orders(), out var warnings);

        Assert.Contains("CREATE TABLE [dbo].[Orders]", sql);
        Assert.Contains("[Id] [INT] IDENTITY(1,1)".Replace("[INT]", "INT"), sql);
        Assert.Contains("[Code] NVARCHAR(50) NOT NULL DEFAULT 'X'", sql);
        Assert.Contains("PRIMARY KEY ([Id])", sql);
        Assert.Empty(warnings);
    }

    [Fact]
    public void TranslateDefault_UnknownFunction_DroppedWithWarning()
    {
        var (kept, warning) = CanonicalDdl.TranslateDefault(
            "dbo.fn_Default()", DatabaseEngine.PostgreSql);

        Assert.Null(kept);
        Assert.NotNull(warning);
    }

    [Theory]
    [InlineData("123", "123")]
    [InlineData("'abc'", "'abc'")]
    [InlineData("N'abc'", "'abc'")]
    [InlineData("GETDATE()", "CURRENT_TIMESTAMP")]
    public void TranslateDefault_CommonCases_Postgres(string input, string expected)
    {
        var (kept, warning) = CanonicalDdl.TranslateDefault(input, DatabaseEngine.PostgreSql);

        Assert.Equal(expected, kept);
        Assert.Null(warning);
    }

    [Theory]
    [InlineData("int", "int(11)", CanonicalType.Int32)]
    [InlineData("bigint", "bigint(20)", CanonicalType.Int64)]
    [InlineData("tinyint", "tinyint(1)", CanonicalType.Bool)]
    [InlineData("tinyint", "tinyint(4)", CanonicalType.Int16)]
    [InlineData("varchar", "varchar(50)", CanonicalType.String)]
    [InlineData("text", "text", CanonicalType.String)]
    [InlineData("decimal", "decimal(10,2)", CanonicalType.Decimal)]
    [InlineData("datetime", "datetime(6)", CanonicalType.DateTime)]
    [InlineData("timestamp", "timestamp", CanonicalType.DateTime)]
    [InlineData("json", "json", CanonicalType.Json)]
